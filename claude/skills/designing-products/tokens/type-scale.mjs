#!/usr/bin/env node
// The type step: a modular scale from a base size and a ratio, written as DESIGN.md's `typography:` roles.
//   node type-scale.mjs --base 16 --ratio 1.25 --body "IBM Plex Sans, sans-serif" \
//     [--display "Fraunces, serif"] [--heading-weight 600] [--print] [DESIGN.md]
// Each role sits on a step of base * ratio^n, rounded to whole pixels; line height tightens and tracking
// closes as the size grows. Exit 1, writing nothing, when the caption falls under 12px, the body under 14px,
// or the ratio leaves 1.067 to 1.618 (our thresholds; type-scale.md). Exit 2 on bad arguments.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseArgs, UsageError, writeGroup } from './palette.mjs';

// [role, step, face]: the step on the scale and which face sets it.
export const ROLES = [['caption', -1, 'body'], ['body', 0, 'body'], ['label', 0, 'body'], ['lead', 1, 'body'],
  ['h3', 2, 'display'], ['h2', 3, 'display'], ['h1', 4, 'display']]; // six sizes: the rubric's B1 ceiling

export function typeScale({ base, ratio, body, display, headingWeight = 600 }) {
  base = Number(base); ratio = Number(ratio); headingWeight = Number(headingWeight);
  if (!(base > 0) || !(ratio > 1) || !body) throw new UsageError('--base, --ratio (> 1) and --body are required');
  display ||= body;
  const typography = {}, problems = [];
  for (const [role, step, face] of ROLES) {
    const size = Math.round(base * ratio ** step);
    typography[role] = {
      fontFamily: face === 'display' ? display : body,
      fontSize: `${size}px`,
      fontWeight: step >= 2 ? headingWeight : role === 'label' ? 600 : 400,
      lineHeight: role === 'label' ? 1.3 : Math.max(1.05, Math.min(1.5, +(1.5 - 0.1 * step).toFixed(2))),
      letterSpacing: step >= 2 ? `${(-0.005 * (step - 1)).toFixed(3)}em` : step < 0 ? '0.01em' : '0em',
    };
  }
  const px = (r) => parseInt(typography[r].fontSize, 10);
  if (ratio < 1.067 || ratio > 1.618) problems.push(`ratio ${ratio} is outside 1.067 to 1.618: steps blur together or jump apart`);
  if (px('caption') < 12) problems.push(`caption is ${px('caption')}px, under 12px: lower the ratio or raise the base`);
  if (px('body') < 14) problems.push(`body is ${px('body')}px, under 14px`);
  return { typography, problems, ok: !problems.length };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [opts, [designPath = 'DESIGN.md']] = parseArgs(process.argv.slice(2), ['--base', '--ratio', '--body', '--display', '--heading-weight']);
  let t;
  try { t = typeScale({ ...opts, headingWeight: opts['heading-weight'] }); } catch (e) { console.error(e.message); process.exit(e instanceof UsageError ? 2 : 1); }
  for (const [role, v] of Object.entries(t.typography)) console.log(`${role.padEnd(8)} ${v.fontSize.padStart(5)} / ${v.lineHeight}  ${v.letterSpacing.padStart(8)}  ${v.fontWeight}  ${v.fontFamily}`);
  if (!t.ok) {
    t.problems.forEach((p) => console.error(`FAIL  ${p}`));
    console.error('refused: nothing written');
    process.exit(1);
  }
  const comment = `generated by type-scale.mjs --base ${opts.base} --ratio ${opts.ratio}; rerun it, do not hand-edit`;
  if (opts.print) console.log(writeGroup('---\n---', 'typography', t.typography, comment).split('\n').slice(1, -1).join('\n'));
  else {
    fs.writeFileSync(designPath, writeGroup(fs.readFileSync(designPath, 'utf8'), 'typography', t.typography, comment));
    console.log(`wrote ${Object.keys(t.typography).length} type roles to ${designPath}`);
  }
}
