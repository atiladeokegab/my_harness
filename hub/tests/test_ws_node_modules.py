import os
import subprocess
import tempfile
import unittest
from pathlib import Path

SCRIPT = Path(__file__).resolve().parent.parent / "bin" / "ws-node-modules"


def sh(*args, cwd=None, env=None):
    return subprocess.run(args, cwd=cwd, env=env, check=True, capture_output=True, text=True)


class WsNodeModules(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.tmp = Path(tmp.name)
        self.main = self.tmp / "main"
        self.main.mkdir()
        sh("git", "init", "-q", cwd=self.main)
        (self.main / "web").mkdir()
        (self.main / "web/package-lock.json").write_text("one")
        sh("git", "-c", "user.email=a@b", "-c", "user.name=t", "add", ".", cwd=self.main)
        sh("git", "-c", "user.email=a@b", "-c", "user.name=t", "commit", "-qm", "x", cwd=self.main)
        (self.main / "web/node_modules/.vite").mkdir(parents=True)
        (self.main / "web/node_modules/dep.js").write_text("dep")
        (self.main / "web/node_modules/.vite/cache").write_text("c")
        self.wt = self.tmp / "wt"
        sh("git", "worktree", "add", "-q", "--detach", str(self.wt), cwd=self.main)
        bindir = self.tmp / "bin"
        bindir.mkdir()
        (bindir / "npm").write_text(f'#!/bin/sh\necho "$PWD $*" >> {self.tmp}/npm.log\n')
        (bindir / "npm").chmod(0o755)
        self.env = {**os.environ, "PATH": f"{bindir}:{os.environ['PATH']}"}

    def run_script(self):
        sh(str(SCRIPT), str(self.wt), env=self.env)

    def test_same_lock_hardlinks(self):
        self.run_script()
        dep = self.wt / "web/node_modules/dep.js"
        self.assertEqual(dep.stat().st_ino, (self.main / "web/node_modules/dep.js").stat().st_ino)
        cache = self.wt / "web/node_modules/.vite/cache"  # vite cache is copied, not shared
        self.assertEqual(cache.read_text(), "c")
        self.assertNotEqual(cache.stat().st_ino, (self.main / "web/node_modules/.vite/cache").stat().st_ino)
        self.assertFalse((self.tmp / "npm.log").exists())

    def test_different_lock_runs_npm_ci(self):
        (self.wt / "web/package-lock.json").write_text("two")
        self.run_script()
        self.assertFalse((self.wt / "web/node_modules").exists())
        self.assertIn("ci --no-audit --no-fund", (self.tmp / "npm.log").read_text())


if __name__ == "__main__":
    unittest.main()
